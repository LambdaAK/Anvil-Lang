MARKS = {".": [[[4, 98], [5, 99], [4, 100]]], ",": [[[6, 96], [5, 104], [1, 114]]], "'": [[[6, 2], [5, 10], [3, 18]]]}


def write(text, seed=0, wobble=1.5, gap=16, space=60, line_height=180):
    """Strokes of `text` written letter by letter, as a person printing with a mouse would:
    a little wobble, slightly uneven spacing; '\\n' starts a new line."""
    import random
    rnd = random.Random(seed)
    strokes, x, y = [], 0.0, 0.0
    for ch in text:
        if ch == "\n":
            x, y = 0.0, y + line_height
            continue
        if ch == " ":
            x += space * rnd.uniform(0.85, 1.15)
            continue
        glyph = GLYPHS[ch] if ch in GLYPHS else MARKS[ch]
        scale = 0.6 if ch.isdigit() else 1.0        # the digits are drawn in a 100-wide box
        dx, dy = rnd.uniform(-2, 2), rnd.uniform(-3, 3)
        left = min(p[0] for s in glyph for p in s) * scale          # the glyph's left edge goes at x
        width = max(p[0] for s in glyph for p in s) * scale - left
        for s in glyph:
            strokes.append([[x + p[0] * scale - left + dx + rnd.gauss(0, wobble), y + p[1] + dy + rnd.gauss(0, wobble)]
                            for p in s])
        x += width + gap * rnd.uniform(0.7, 1.3)
    return strokes
