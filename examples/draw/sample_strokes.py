"""Digits drawn the way a person draws them with a mouse: strokes of points, y going down.
Used to test the drawing app's pipeline (strokes -> MNIST-like image -> network) without a person."""
import math


def arc(cx, cy, rx, ry, a0, a1, n=24):
    """Points on an ellipse from angle a0 to a1 (degrees, 0 = right, 90 = down)."""
    return [[cx + rx * math.cos(math.radians(a0 + (a1 - a0) * k / n)),
             cy + ry * math.sin(math.radians(a0 + (a1 - a0) * k / n))] for k in range(n + 1)]


