def variants(strokes, n, seed):
    """n wobbly, stretched and slanted copies of a drawing, as different people might draw it."""
    import random
    rnd = random.Random(seed)
    out = []
    for _ in range(n):
        sx, sy = rnd.uniform(0.75, 1.25), rnd.uniform(0.85, 1.15)
        slant = rnd.uniform(-0.2, 0.2)
        size = rnd.uniform(0.5, 3.0)                       # small or large drawings
        out.append([[[size * (sx * x + slant * (y - 50) + rnd.gauss(0, 1.2)), size * (sy * y + rnd.gauss(0, 1.2))]
                     for x, y in s] for s in strokes])
    return out


